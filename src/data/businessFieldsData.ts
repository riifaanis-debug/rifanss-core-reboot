export const getSubServiceById = (serviceId: string): { subService: SubServiceItem; field: BusinessFieldItem } | null => {
  for (const field of BUSINESS_FIELDS_DATA) {
    const sub = field.subServices.find(s => s.id === serviceId);
    if (sub) {
      return { subService: sub, field };
    }
  }
  return null;
};

export const getAllSubServices = (): (SubServiceItem & { fieldId: string; fieldTitle: string })[] => {
  const result: (SubServiceItem & { fieldId: string; fieldTitle: string })[] = [];
  for (const field of BUSINESS_FIELDS_DATA) {
    for (const sub of field.subServices) {
      result.push({
        ...sub,
        fieldId: field.id,
        fieldTitle: field.title,
      });
    }
  }
  return result;
};

